def lua_policy_table(obj, indent=""):
    if isinstance(obj, dict):
        lines = ["{"]
        for k in sorted(obj.keys()):
            v = obj[k]
            lines.append(f"{indent}  [{lua_string(k)}] = {lua_policy_table(v, indent + '  ')},")
        lines.append(indent + "}")
        return "\n".join(lines)

    if isinstance(obj, list):
        # Lists are enum values.
        return lua_set(obj, indent)

    if isinstance(obj, bool):
        return "true" if obj else "false"

    if isinstance(obj, (int, float)):
        return str(obj)

    return lua_string(obj)


def build_policy(modules):
    action_modules = {}
    query_submodules = {}
    global_params = {}

    for key, mod in modules.items():
        name = mod.get("name")
        path = mod.get("path") or name

        params = module_to_policy(mod)

        if path == "main":
            global_params = params
            continue

        if path and path.startswith("query+"):
            parts = path.split("+", 1)
            sub = parts[1]
            group = mod.get("group") or guess_query_group(name, sub)

            query_submodules.setdefault(group, {})[name] = params
            continue

        if name:
            action_modules[name] = params

    return {
        "global_params": global_params,
        "action_modules": action_modules,
        "query_submodules": query_submodules,
    }


def guess_query_group(name, sub):
    # Common query module families.
    # MediaWiki paraminfo usually includes enough metadata, but this fallback helps.
    if name in {
        "info", "revisions", "images", "imageinfo", "links", "langlinks",
        "categories", "templates", "contributors", "extracts", "pageprops",
    }:
        return "prop"

    if name in {
        "allpages", "allimages", "allusers", "categorymembers",
        "backlinks", "embeddedin", "search", "recentchanges", "logevents",
    }:
        return "list"

    if name in {
        "siteinfo", "userinfo", "tokens", "filerepoinfo", "languageinfo",
        "notifications",
    }:
        return "meta"

    return "prop"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("base_url", help="Example: http://localhost:8889/")
    ap.add_argument("--json-output", default="mediawiki-api-paraminfo.json")
    ap.add_argument("--lua-output", default="mediawiki.lua")
    args = ap.parse_args()

    api_url = args.base_url.rstrip("/") + "/api.php"

    seeds = ["main", "*", "query+**"]

    modules = get_modules(api_url, seeds)
    names = sorted({m.get("path") or m.get("name") for m in modules if m.get("name")})
    more = get_modules(api_url, names)

    by_name = {}
    for m in modules + more:
        key = m.get("path") or m.get("name")
        if key:
            by_name[key] = m

    result = {
        "api_url": api_url,
        "module_count": len(by_name),
        "modules": dict(sorted(by_name.items())),
    }

    with open(args.json_output, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)

    policy = build_policy(by_name)
    lua = generate_lua(policy)

    with open(args.lua_output, "w", encoding="utf-8") as f:
        f.write(lua)

    print(f"Wrote {args.json_output}")
    print(f"Wrote {args.lua_output}")
    print(f"Modules found: {len(by_name)}")
    print(f"Action modules: {len(policy['action_modules'])}")
    print(f"Query families: {', '.join(sorted(policy['query_submodules']))}")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)


