def api_get(api_url, params):
    params = dict(params)
    params.setdefault("format", "json")
    url = api_url + "?" + urllib.parse.urlencode(params, doseq=True)
    with urllib.request.urlopen(url) as r:
        return json.loads(r.read().decode("utf-8"))


def chunks(items, size):
    for i in range(0, len(items), size):
        yield items[i:i + size]


def get_modules(api_url, modules):
    out = []
    for chunk in chunks(modules, 50):
        data = api_get(api_url, {
            "action": "paraminfo",
            "modules": "|".join(chunk),
            "helpformat": "none",
        })
        out.extend(data.get("paraminfo", {}).get("modules", []))
    return out


def lua_string(s):
    return json.dumps(str(s))


def lua_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return lua_string(v)


def lua_set(values, indent=""):
    lines = ["{"]
    for v in sorted(str(x) for x in values):
        lines.append(f'{indent}  [{lua_string(v)}] = true,')
    lines.append(indent + "}")
    return "\n".join(lines)


def normalize_type(t):
    if isinstance(t, list):
        return {
            "kind": "enum",
            "values": [str(x) for x in t],
        }

    if not isinstance(t, str):
        return {"kind": "string"}

    t = t.lower()

    if t in ("boolean", "bool"):
        return {"kind": "boolean"}
    if t in ("integer", "int", "limit", "namespace"):
        return {"kind": "integer"}
    if t in ("timestamp",):
        return {"kind": "timestamp"}

    return {"kind": "string"}


def module_to_policy(mod):
    params = {}

    for p in mod.get("parameters", []):
        name = p.get("name")
        if not name:
            continue

        nt = normalize_type(p.get("type"))

        params[name] = {
            "required": bool(p.get("required")),
            "multi": bool(p.get("multi")),
            "type": nt["kind"],
        }

        if nt["kind"] == "enum":
            params[name]["values"] = nt["values"]

    return params


